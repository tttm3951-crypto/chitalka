def plural(n, forms) -> str:
    """1 рубль, 2 рубля, 5 рублей; дробные — «2,5 рубля»."""
    s = str(n)
    if "," in s or "." in s:
        return forms[1]
    n = abs(int(s)) % 100
    if 11 <= n <= 14:
        return forms[2]
    return forms[0] if n % 10 == 1 else forms[1] if 2 <= n % 10 <= 4 else forms[2]


def _units(m):
    num, u = m.group(1), m.group(2).rstrip(".")
    return f"{num} {plural(num, _UNITS[u])}"


_CASE_OF = {"век": "nom", "века": "gen", "веке": "prep", "веком": "ins", "веку": "prep",
            "веков": "gen", "веках": "prep", "веками": "ins", "вв.": "nom", "в.": "nom"}


def _sentence_dot(m, rep_text):
    """Сокращение стояло в конце предложения — точку оставляем (иначе голос не сделает паузу)."""
    rest = m.string[m.end():]
    if not rest.strip() or re.match(r"\s+[А-ЯЁA-Z]", rest):
        return rep_text + "."
    return rep_text


def expand(t: str) -> str:
    # «Глава IV», «Часть 2» → порядковые
    def fem(m):
        n = roman(m.group(2)) if m.group(2).isalpha() else int(m.group(2))
        return f"{m.group(1)} {ordinal(n, 'f')}" if n else m.group(0)

    def masc(m):
        n = roman(m.group(2)) if m.group(2).isalpha() else int(m.group(2))
        return f"{m.group(1)} {ordinal(n, 'm')}" if n else m.group(0)

    t = re.sub(_FEM_NOUNS + r"\s+" + _NUM + r"\b(?![.,]\d)", fem, t)
    t = re.sub(_MASC_NOUNS + r"\s+" + _NUM + r"\b(?![.,]\d)", masc, t)

    # века: «XIX век», «в XX веке», «в XIII в.», «XVIII–XIX вв.», «в VII и VIII веках»
    def cent(m):
        pre, a_r, sep, b_r, word = m.group(1) or "", m.group(2), m.group(3), m.group(4), m.group(5)
        a = roman(a_r)
        b = roman(b_r) if b_r else 0
        if not a or (b_r and not b):
            return m.group(0)
        wl = word.lower()
        case = _CASE_OF[wl]
        if wl in ("в.", "вв.") and pre.strip().lower() in ("в", "во"):
            case = "prep"
        if wl == "века" and b:  # «XVIII–XIX века» — именительный множественного
            case = "nom"
        spoken = {"в.": "веке" if case == "prep" else "век",
                  "вв.": "веках" if case == "prep" else "века"}.get(wl, word)
        if b:
            joiner = " и " if sep.strip() == "и" else " — "
            out = f"{ordinal(a, 'm', case)}{joiner}{ordinal(b, 'm', case)} {spoken}"
        else:
            out = f"{ordinal(a, 'm', case)} {spoken}"
        res = pre + out
        return _sentence_dot(m, res) if word.endswith(".") else res

    t = re.sub(r"(\b(?:в|во|В|Во)\s+)?\b([IVXLC]{1,6})(?:(\s*[–—-]\s*|\s+и\s+)([IVXLC]{1,6}))?\s+"
               r"(веками|веках|веков|веком|веке|веку|века|век|вв\.|в\.)(?!\w)", cent, t)
    # «Пётр I», «Людовик XIV» → «Пётр Первый»
    t = re.sub(r"\b([А-ЯЁ][а-яё]{2,})\s+([IVX]{1,5})\b(?![.\w-])",
               lambda m: (m.group(1) + " " + ordinal(roman(m.group(2)), "m").capitalize()) if roman(m.group(2))
               else m.group(0), t)
    # единицы с числом: «5 руб.», «3 млн», «30 см», «0,2 г», «40 °C»
    t = re.sub(r"(\d+(?:,\d+)?)\s*(руб\.|коп\.|тыс\.|млн\.?|млрд\.?)(?![а-яё])", _units, t)
    t = re.sub(r"(\d+(?:,\d+)?)\s*(см|мм|км|кг|мг|мл|°C|°)(?![а-яёa-z/²³])", _units, t)
    t = re.sub(r"(\d+,\d+|\b\d{1,3})\s*(г)(?![а-яё.\w])", _units, t)
    # «и др.»: перед существительным в родительном — «и других заболеваний»
    t = re.sub(r"\bи\s+др\.(\s+)(?=[а-яё]+(?:ий|ей|ов|ев|ых|их|ат|ят)\b)", r"и других\1", t)
    t = re.sub(r"\bи\s+др\.", lambda m: _sentence_dot(m, "и другие"), t)
    for rx, rep, dot in _ABBR:
        t = rx.sub((lambda m, rep=rep: _sentence_dot(m, m.expand(rep))) if dot else rep, t)
    return t


