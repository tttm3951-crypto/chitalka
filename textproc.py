"""
Подготовка текста к озвучке:
  clean_paragraphs — убирает «мусор» (ISBN, УДК/ББК, ©, сноски [1], звёздочки);
  expand           — числа и сокращения словами («Глава IV» → «Глава четвёртая», «т. д.» → «так далее»);
  homographs       — ударения в омографах по смыслу («висячий замок» → замо́к).
"""
from __future__ import annotations

import re

STRESS = "\u0301"

# ============================================================================ чистка мусора
_ISBN = re.compile(r"\bISBN[\s:\u2011\-]*[\dXxХх][\dXxХх\s\u2011\-–]{8,}[\dXxХх]", re.I)
_DROP_PAR = re.compile(r"^\s*(ISBN\b|УДК\b|ББК\b|LCC\b|DDC\b|©|\(c\)\s|Все права защищены|"
                       r"All rights reserved|Литературно-художественное издание|Подписано в печать|"
                       r"Формат \d+\s*[x×х]\s*\d+|Тираж \d+|Заказ №)", re.I)
_BRACKET_REF = re.compile(r"\s?\[(?:\d{1,3}(?:\s*[,–\-]\s*\d{1,3})*|\d{1,3}\s*,\s*[сc]\.\s*\d+(?:[–\-]\d+)?|"
                          r"[сc]\.\s*\d+(?:[–\-]\d+)?)\]")
_STAR_NOTE = re.compile(r"(?<=[\w»\".,!?])\*{1,3}(?=[\s,.;:!?»)]|$)")
_SUP_NOTE = re.compile(r"(?<=[\w».,!?])[¹²³⁴⁵⁶⁷⁸⁹⁰]+")


def clean_paragraph(p: str) -> str:
    p = _ISBN.sub("", p)
    p = _BRACKET_REF.sub("", p)
    p = _STAR_NOTE.sub("", p)
    p = _SUP_NOTE.sub("", p)
    return re.sub(r"[ \t]{2,}", " ", p).strip()


_IMPRINT = re.compile(r"Гарнитура|Формат\s*\d+\s*[xх×]\s*\d+|печ\.\s*л\.|Тираж\b|Заказ\s*№|Подписано в печать|"
                      r"\bISBN\b|\bУДК\b|\bББК\b|Издательство|Отпечатано|Бумага офсетная|Печать офсетная|"
                      r"Лицензия|Санитарно-эпидемиологическ|тел\.|Телефон/факс|e-mail|www\.", re.I)


def clean_paragraphs(paragraphs: list[str], chapters: list[tuple[str, int]]):
    """Чистит абзацы и выбрасывает служебные (выходные данные). Возвращает (абзацы, главы) с новыми номерами."""
    out, remap = [], {}
    for i, p in enumerate(paragraphs):
        remap[i] = len(out)
        if len(p) < 300 and _DROP_PAR.match(p):
            continue
        if len(p) < 600 and len(set(m.group(0).lower()[:6] for m in _IMPRINT.finditer(p))) >= 2:
            continue  # выходные данные издательства
        c = clean_paragraph(p)
        if c and re.search(r"\w", c):
            out.append(c)
    new_ch = []
    for t, pi in chapters:
        j = remap.get(pi, len(out))
        if j < len(out) and (not new_ch or new_ch[-1][1] != j):
            new_ch.append((t, j))
    return out, new_ch


# ============================================================================ числа и сокращения
_ROMAN_V = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100}


def roman(s: str) -> int:
    s = s.upper()
    if not s or not re.fullmatch(r"M{0,3}(CM|CD|D?C{0,3})(XC|XL|L?X{0,3})(IX|IV|V?I{0,3})", s):
        return 0
    v = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100, "D": 500, "M": 1000}
    total = 0
    for i, ch in enumerate(s):
        x = v[ch]
        total += -x if i + 1 < len(s) and v[s[i + 1]] > x else x
    return total


def ordinal(n: int, gender: str = "m", case: str = "nom") -> str:
    """Порядковое числительное: ordinal(4, 'f') → «четвёртая», ordinal(19, 'm', 'prep') → «девятнадцатом»."""
    try:
        from num2words import num2words
        words = num2words(n, lang="ru", to="ordinal").split()
    except Exception:  # noqa: BLE001
        return str(n)
    last = words[-1]
    if last == "третий":
        stem, kind = "трет", "soft"
    elif last.endswith(("ый", "ий", "ой")):
        stem, kind = last[:-2], last[-2:]
    else:
        return " ".join(words)
    if kind == "soft":
        forms = {("m", "nom"): "ий", ("m", "gen"): "ьего", ("m", "prep"): "ьем", ("m", "ins"): "ьим",
                 ("f", "nom"): "ья", ("f", "gen"): "ьей", ("f", "prep"): "ьей", ("f", "ins"): "ьей",
                 ("n", "nom"): "ье", ("p", "gen"): "ьих", ("p", "nom"): "ьи"}
    else:
        hard_m = "ой" if kind == "ой" else "ый"
        forms = {("m", "nom"): hard_m, ("m", "gen"): "ого", ("m", "prep"): "ом", ("m", "ins"): "ым",
                 ("f", "nom"): "ая", ("f", "gen"): "ой", ("f", "prep"): "ой", ("f", "ins"): "ой",
                 ("n", "nom"): "ое", ("p", "gen"): "ых", ("p", "nom"): "ые"}
    words[-1] = stem + forms.get((gender, case), forms[("m", "nom")])
    return " ".join(words)


