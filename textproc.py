_HG = []
for word, default, rules in HOMOGRAPHS:
    _HG.append((re.compile(r"(?<![\w" + STRESS + r"])" + word + r"(?![\w" + STRESS + r"])", re.I), default,
                [(re.compile(rx, re.I), st) for rx, st in rules]))


def _to_stress(s: str) -> str:
    return re.sub(r"\+([аеёиоуыэюяАЕЁИОУЫЭЮЯ])", lambda m: m.group(1) + STRESS, s)


def homographs(t: str) -> str:
    """Ставит ударение в омографах по словам рядом в том же предложении."""
    low = t.lower()
    for rx, default, rules in _HG:
        if not rx.search(t):
            continue

        def sub(m):
            w = m.group(0)
            if STRESS in t[m.start():m.end() + 1]:
                return w
            a, b = max(0, m.start() - 70), min(len(t), m.end() + 70)
            ctx = low[a:b]
            choice = default
            for crx, st in rules:
                if crx.search(ctx):
                    choice = st
                    break
            out = _to_stress(choice)
            return out[:1].upper() + out[1:] if w[:1].isupper() else out

        t = rx.sub(sub, t)
    return t
